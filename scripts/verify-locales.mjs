#!/usr/bin/env node
/**
 * CV-115: assert en/it play-shell locale files exist with identical key trees
 * and required lobby / game / offers coverage for the M1 play shell.
 */
import { readFileSync, existsSync } from "node:fs"
import { dirname, join, resolve } from "node:path"
import { fileURLToPath } from "node:url"

const __dirname = dirname(fileURLToPath(import.meta.url))
const repoRoot = resolve(__dirname, "..")

const LOCALES = ["en", "it"]
const FILE_NAME = "play-shell.json"

/** Required top-level sections and a sample of leaf keys each section must own. */
const REQUIRED = {
  lobby: [
    "title",
    "quickPair",
    "quickPairCancel",
    "seekCreate",
    "seekCancel",
    "seekEmpty",
    "challengeFriend",
    "challengeLink",
    "challengeAccept",
    "challengeDecline",
    "challengeExpired",
    "waiting",
    "rated",
    "casual",
    "colorRandom",
    "colorWhite",
    "colorBlack",
    "timeBullet",
    "timeBlitz",
    "timeRapid",
    "timeClassical",
    "timeCorrespondence",
    "matchmakingUnavailable",
  ],
  game: [
    "yourTurn",
    "opponentTurn",
    "white",
    "black",
    "clock",
    "resign",
    "abort",
    "confirmResign",
    "confirmAbort",
    "opponentDisconnected",
    "reconnecting",
    "youWin",
    "youLose",
    "drawResult",
    "drawAgreement",
    "opponentResigned",
    "youResigned",
    "aborted",
    "check",
    "checkmate",
    "stalemate",
    "timeout",
    "insufficientMaterial",
    "threefold",
    "fiftyMove",
    "fivefold",
    "abortDenied",
    "illegalMove",
    "notYourTurn",
    "offerInvalid",
    "gameGone",
    "spectating",
    "moveAnnounced",
    "ratingDiff",
  ],
  offers: [
    "drawOffer",
    "drawIncoming",
    "takebackOffer",
    "takebackIncoming",
    "rematchOffer",
    "rematchIncoming",
    "pending",
    "accept",
    "decline",
    "withdraw",
  ],
}

const FORBIDDEN_COPY =
  /\b(Stockfish|Leela|lc0|Lichess|Chess\.com|Crowdin|Lokalise|ChatGPT|Claude|Copilot|LLM|generated by|assisted by)\b/i

const emojiRe = /[\u{1F300}-\u{1FAFF}\u{2600}-\u{27BF}]/u

let failed = 0
const fail = (msg) => {
  console.error(`FAIL: ${msg}`)
  failed += 1
}
const ok = (msg) => console.log(`OK: ${msg}`)

const flattenKeys = (value, prefix = "", out = []) => {
  if (value === null || typeof value !== "object" || Array.isArray(value)) {
    out.push(prefix)
    return out
  }
  const keys = Object.keys(value).sort()
  if (keys.length === 0) {
    out.push(prefix)
    return out
  }
  for (const key of keys) {
    const next = prefix ? `${prefix}.${key}` : key
    flattenKeys(value[key], next, out)
  }
  return out
}

const assertStringLeaves = (value, path, locale) => {
  if (typeof value === "string") {
    if (value.trim().length === 0) {
      fail(`${locale}: empty string at ${path}`)
    }
    if (emojiRe.test(value)) {
      fail(`${locale}: emoji in string at ${path}`)
    }
    if (/TODO|FIXME|TBD|lorem ipsum|xxx/i.test(value)) {
      fail(`${locale}: placeholder copy at ${path}`)
    }
    if (FORBIDDEN_COPY.test(value)) {
      fail(`${locale}: forbidden third-party or attribution wording at ${path}`)
    }
    return
  }
  if (value === null || typeof value !== "object" || Array.isArray(value)) {
    fail(`${locale}: leaf at ${path} must be a string`)
    return
  }
  for (const key of Object.keys(value)) {
    assertStringLeaves(value[key], path ? `${path}.${key}` : key, locale)
  }
}

const catalogs = {}

for (const locale of LOCALES) {
  const path = join(repoRoot, locale, FILE_NAME)
  if (!existsSync(path)) {
    fail(`missing ${locale}/${FILE_NAME}`)
    continue
  }
  let parsed
  try {
    parsed = JSON.parse(readFileSync(path, "utf8"))
  } catch (err) {
    fail(`${locale}/${FILE_NAME}: invalid JSON (${err.message})`)
    continue
  }
  if (parsed === null || typeof parsed !== "object" || Array.isArray(parsed)) {
    fail(`${locale}/${FILE_NAME}: root must be a JSON object`)
    continue
  }
  catalogs[locale] = parsed
  ok(`${locale}/${FILE_NAME} parses`)
  assertStringLeaves(parsed, "", locale)
}

if (LOCALES.every((locale) => catalogs[locale])) {
  const keySets = Object.fromEntries(
    LOCALES.map((locale) => [locale, flattenKeys(catalogs[locale]).sort()])
  )
  const base = keySets.en
  for (const locale of LOCALES) {
    if (locale === "en") continue
    const other = keySets[locale]
    const missing = base.filter((k) => !other.includes(k))
    const extra = other.filter((k) => !base.includes(k))
    if (missing.length) {
      fail(`${locale}: missing keys vs en: ${missing.join(", ")}`)
    }
    if (extra.length) {
      fail(`${locale}: extra keys vs en: ${extra.join(", ")}`)
    }
  }
  if (!failed) ok("en and it key trees match")

  for (const [section, keys] of Object.entries(REQUIRED)) {
    if (!(section in catalogs.en)) {
      fail(`en: missing required section "${section}"`)
      continue
    }
    for (const key of keys) {
      const leaf = catalogs.en[section]?.[key]
      if (typeof leaf !== "string" || leaf.trim().length === 0) {
        fail(`en: required key ${section}.${key} missing or empty`)
      }
    }
  }
  if (!failed) {
    ok(
      `required play-shell keys present (${Object.keys(REQUIRED).join(", ")})`
    )
  }

  // Italian must differ on at least some user-facing strings (not a copy of en).
  let differing = 0
  for (const path of base) {
    const parts = path.split(".")
    let enVal = catalogs.en
    let itVal = catalogs.it
    for (const part of parts) {
      enVal = enVal?.[part]
      itVal = itVal?.[part]
    }
    if (typeof enVal === "string" && typeof itVal === "string" && enVal !== itVal) {
      differing += 1
    }
  }
  if (differing < 10) {
    fail(
      `it looks like a near-copy of en (${differing} differing leaves; expect substantial Italian)`
    )
  } else {
    ok(`it differs from en on ${differing} leaves`)
  }

  // Interpolation placeholders must match between locales.
  const placeholderRe = /\{\{\s*([a-zA-Z0-9_]+)\s*\}\}/g
  for (const path of base) {
    const parts = path.split(".")
    let enVal = catalogs.en
    let itVal = catalogs.it
    for (const part of parts) {
      enVal = enVal?.[part]
      itVal = itVal?.[part]
    }
    if (typeof enVal !== "string" || typeof itVal !== "string") continue
    const enPh = [...enVal.matchAll(placeholderRe)].map((m) => m[1]).sort()
    const itPh = [...itVal.matchAll(placeholderRe)].map((m) => m[1]).sort()
    if (enPh.join(",") !== itPh.join(",")) {
      fail(
        `placeholder mismatch at ${path}: en={${enPh}} it={${itPh}}`
      )
    }
  }
  if (!failed) ok("interpolation placeholders match across locales")
}

if (failed) {
  console.error(`\n${failed} locale check(s) failed.`)
  process.exit(1)
}

console.log("All CV-115 play-shell locale checks passed.")
